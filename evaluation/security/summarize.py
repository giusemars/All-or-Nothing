BUF = 256  # cat's read buffer (cat.c)


def rd(*p, default=""):
    try:
        with open(os.path.join(*p), "rb") as f:
            return f.read().decode(errors="replace").strip()
    except FileNotFoundError:
        return default


def sha(path):
    """sha256 of @path, or of the file it was replaced by (see run_security.sh)."""
    if not os.path.exists(path):
        return rd(path + ".sha256").split()[0]
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def klog(i):
    return [l for l in rd(runs, i + ".klog").splitlines() if l]


def blocked(i):
    return [l for l in klog(i) if "BLOCKED" in l]


def execve_ran(i):
    return "[attacker]" in rd(runs, i + ".stdout")


def measured(i):
    """System calls in the strace of run @i, minus the execve of the program
    itself (issued by the parent, not through a wrapper)."""
    c = {l.split()[0]: int(l.split()[1]) for l in rd(runs, i + ".calls").splitlines()}
    if not c:
        return "—"
    return str(sum(c.values()) - 1) if c.get("execve") == 1 else "%s?" % c


def code(lines):
    return "```\n" + "\n".join(lines) + "\n```"


