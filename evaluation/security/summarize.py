# ---------------------------------------------------------------- strace
def strace_entries(i):
    """[(header, [frames])] of runs/<i>.strace (strace -n -k)."""
    ents = []
    for l in rd(runs, i + ".strace").splitlines():
        if l.startswith(" > "):
            if ents:
                ents[-1][1].append(l[3:])
        else:
            ents.append((l, []))
    return ents


def frame(f):
    """'/path/bin(sym+0x9) [0x1cd8]' -> 'bin(sym+0x9)'."""
    path, _, rest = f.partition("(")
    return "%s(%s" % (os.path.basename(path), rest.split(" [")[0])


def ours(fr, binname):
    return fr.startswith(binname + "(")


def in_block(fr):
    sym = fr.partition("(")[2]
    return sym.startswith(("__aon_", "sys_"))


def excerpt(i, binname):
    """The trace of run @i trimmed for the reader: the program's own execve,
    _start frames, single-steps in ordinary code, and the /bin/echo that a
    successful hijack runs are elided (the full file is runs/<i>.strace)."""
    out_, elided, stderr_writes = [], 0, 0
    ents = strace_entries(i)[1:]
    k = 0
    while k < len(ents):
        hdr, frs = ents[k]
        frs = [frame(f) for f in frs]
        if frs and not ours(frs[0], binname) or (not frs and "exited" not in hdr
                                                 and k and "execve(" in ents[k - 1][0]):
            out_.append("[... the attacker's /bin/echo runs: %d more system "
                        "calls elided ...]" % (len(ents) - k))
            break
        frs = [f for f in frs if "(_start" not in f]
        if "--- SIGTRAP" in hdr and not (frs and in_block(frs[0])):
            # single-step in ordinary code: elide it and its rt_sigreturn
            elided += 1
            k += 2 if k + 1 < len(ents) and "rt_sigreturn" in ents[k + 1][0] else 1
            continue
        if elided:
            out_.append("[... %d single-step SIGTRAP + rt_sigreturn in ordinary "
                        "code elided ...]" % elided)
            elided = 0
        if "write(2," in hdr:
            stderr_writes += 1
            k += 1
            continue
        if stderr_writes:
            out_.append("[... %d write(2, ...) of the program's report elided ...]"
                        % stderr_writes)
            stderr_writes = 0
        out_.append(hdr)
        out_ += ["    > " + f for f in frs]
        k += 1
    if stderr_writes:
        out_.append("[... %d write(2, ...) of the program's report elided ...]"
                    % stderr_writes)
    return out_


def find(i, pred):
    for hdr, frs in strace_entries(i)[1:]:
        if pred(hdr):
            return hdr, [frame(f) for f in frs if "(_start" not in frame(f)]
    return None, []


def ret(hdr):
    return hdr.rsplit(" = ", 1)[1] if hdr and " = " in hdr else "—"


